def top_k_filter(probs, k):
    topk_vals, topk_idx = torch.topk(probs, k)
    mask = torch.zeros_like(probs).scatter_(-1, topk_idx, 1.0)
    filtered = probs * mask
    filtered = filtered / filtered.sum(dim=-1, keepdim=True)
    return filtered, topk_idx, topk_vals

# ── N-GRAM SCORING ────────────────────────────────────────────────────────────
def ngram_score(sequence, pos, candidate, n):
    """
    Score candidate token at position pos using n-gram context.
    Uses left context only (fast + causal approximation).
    """
    if pos < n - 1:
        return 0.0  # not enough context

    context = sequence[pos - (n - 1):pos]
    ngram = tuple(context + [candidate])
    return ngram_table.get(ngram, -8.0)


def apply_ngram_grammar_filter(probs, input_ids, n):
    """
    Reweight probabilities using n-gram grammar scores.
    Only applied to TOP-K tokens (already filtered).
    """
    probs_np = probs.cpu().numpy()
    new_probs = np.zeros_like(probs_np)

    for i in range(len(input_ids)):
        token_probs = probs_np[i]
        candidates = np.where(token_probs > 0)[0]

        scores = []
        for tok in candidates:
            score = ngram_score(input_ids, i, tok, n)
            scores.append(score)

