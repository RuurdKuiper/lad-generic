def mask_assistant_tokens_random_amount(
    input_ids,
    tokenizer,
    mask_token="MASK",
    min_ratio=0.0,
    max_ratio=1.0,
):
    mask_id = tokenizer.convert_tokens_to_ids(mask_token)
    eos_id = tokenizer.eos_token_id

    assistant_marker = tokenizer.encode(
        "<|start_header_id|>assistant<|end_header_id|>",
        add_special_tokens=False
    )

    # --- find assistant start ---
    start = None
    for i in range(len(input_ids) - len(assistant_marker)):
        if input_ids[i:i+len(assistant_marker)] == assistant_marker:
            start = i + len(assistant_marker)
            break

    if start is None or start >= len(input_ids):
        return input_ids, input_ids

    corrupted = input_ids.copy()
    labels = input_ids.copy()

    # --- find the end of the actual answer ---
    # The answer ends at the first eos token after `start`.
    end_of_answer = len(input_ids)
    if eos_id in input_ids[start:]:
        end_of_answer = start + input_ids[start:].index(eos_id)

    # 🔥 sample GLOBAL corruption strength per example
    mask_ratio = random.uniform(min_ratio, max_ratio)

    def apply_exact_ratio_mask(start_idx, end_idx):
        length = end_idx - start_idx
        if length <= 0:
            return

        # Calculate exactly how many tokens to mask based on the ratio
        num_to_mask = int(round(length * mask_ratio))

        # Randomly select exact indices to mask in this segment
        indices = range(start_idx, end_idx)
        mask_indices = random.sample(indices, num_to_mask)

        for idx in mask_indices:
            corrupted[idx] = mask_id

    # 1. Mask exactly `mask_ratio` proportion of the actual answer tokens
    apply_exact_ratio_mask(start, end_of_answer)

    # 2. Mask exactly `mask_ratio` proportion of the remaining EOS/pad tokens
    apply_exact_ratio_mask(end_of_answer, len(input_ids))

    return corrupted, labels

