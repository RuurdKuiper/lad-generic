def check_bidirectional_attention(model, tokenizer, dataset, temperature=0.3, num_runs=3):
    model.eval()
    device = next(model.parameters()).device

    # get MASK token id (you said it's literally "MASK")
    mask_token_id = tokenizer("MASK", add_special_tokens=False)["input_ids"][0]

    results = []

    for run in range(num_runs):
        idx = int(np.random.randint(0, len(dataset)))
        sample = dataset[idx]

        assistant_marker = tokenizer.encode(
            "<|start_header_id|>assistant<|end_header_id|>",
            add_special_tokens=False
        )
        input_ids = sample['labels']

        # --- find assistant start ---
        start = None
        for i in range(len(input_ids) - len(assistant_marker)):
            if input_ids[i:i+len(assistant_marker)] == assistant_marker:
                start = i + len(assistant_marker)
                print(start)
                break

        split = start + 5

        input_ids = torch.tensor(input_ids, dtype=torch.long).to(device)
        seq_len = input_ids.shape[0]

        corrupted = input_ids.clone()
        corrupted[start:split] = mask_token_id
        corrupted = corrupted.unsqueeze(0)

        with torch.no_grad():
            logits = model(input_ids=corrupted)["logits"]

        probs = F.softmax(logits / temperature, dim=-1)
        preds = torch.argmax(probs, dim=-1).squeeze(0)

        original = input_ids
        reconstructed = preds

        acc = (reconstructed[:split] == original[:split]).float().mean().item()
        results.append(acc)

        # decode for inspection
        orig_text = tokenizer.decode(original[start:start+20].tolist(), skip_special_tokens=False)
        corrupt_text = tokenizer.decode(corrupted.squeeze(0)[start:start+20].tolist(), skip_special_tokens=False)
        pred_text = tokenizer.decode(reconstructed[start:start+20].tolist(), skip_special_tokens=False)

        print("\n" + "="*80)
        print(f"🔬 Run {run+1}")
        print(f"Reconstruction accuracy (first half): {acc:.3f}")

        if acc > 0.5:
            print("✅ Likely bidirectional (uses future context)")
        elif acc > 0.2:
            print("⚠️ Partial signal")
        else:
            print("❌ Likely causal")

        print("-"*80)
        print("📥 Corrupted input:\n", corrupt_text)
        print("\n🤖 Prediction:\n", pred_text)
        print("\n✅ Original:\n", orig_text)
        print("="*80)

    print("\n📊 Average accuracy:", np.mean(results))

