from dataclasses import dataclass
from typing import List, Dict, Any
import random
import torch

@dataclass
class DiffusionDataCollator:
    eos_token_id: int
    device: torch.device | None = None
    pad_to_multiple_of: int | None = None
    multi_turn_prob: float = 0.5  # Probability of prepending prior turn context
    max_history_turns: int = 2     # Max prior turns to prepend (1 or 2)

    def _remove_extra_eos_padding(
        self,
        input_ids: list[int],
        labels: list[int],
    ) -> tuple[list[int], list[int]]:
        """
        Remove repeated EOS padding while preserving one EOS token
        marking the actual end of the sequence.
        """
        if len(input_ids) != len(labels):
            raise ValueError("input_ids and labels must have equal lengths.")

        end = len(input_ids)
        while (
            end > 1
            and input_ids[end - 1] == self.eos_token_id
            and input_ids[end - 2] == self.eos_token_id
        ):
            end -= 1

        return input_ids[:end], labels[:end]

    def __call__(
        self,
        features: List[Dict[str, Any]],
    ) -> Dict[str, torch.Tensor]:

        # 1. Clean individual features first
        cleaned_features = []
        for feature in features:
            input_ids, labels = self._remove_extra_eos_padding(
                list(feature["input_ids"]),
                list(feature["labels"]),
            )
            cleaned_features.append({
                "input_ids": input_ids,
                "labels": labels,
            })

        batch_size = len(cleaned_features)
        combined_features = []

        # 2. Combine history turns with target turns
        for i, target_feature in enumerate(cleaned_features):
            # Decide whether to prepend history for this sample
            num_history = 0
            if (
                self.multi_turn_prob > 0
                and batch_size > 1
                and random.random() < self.multi_turn_prob
            ):
                num_history = random.randint(1, min(self.max_history_turns, batch_size - 1))

            combined_input_ids = []
            combined_labels = []

            if num_history > 0:
                # Randomly pick prior features from the batch (excluding current target)
                available_indices = [idx for idx in range(batch_size) if idx != i]
                history_indices = random.sample(available_indices, num_history)

                for h_idx in history_indices:
                    hist_feature = cleaned_features[h_idx]
                    # CRITICAL: For historical turns, use the ground-truth labels
                    # for BOTH input_ids and labels (clean context).
                    clean_context = hist_feature["labels"]
                    combined_input_ids.extend(clean_context)
                    combined_labels.extend(clean_context)

            # Append the actual target turn (noised input_ids, target labels)
            combined_input_ids.extend(target_feature["input_ids"])
            combined_labels.extend(target_feature["labels"])

            combined_features.append({
                "input_ids": combined_input_ids,
                "labels": combined_labels,
            })

        # 3. Calculate max length for padding
        batch_max_length = max(
            len(feature["input_ids"]) for feature in combined_features
        )

        if self.pad_to_multiple_of is not None:
            multiple = self.pad_to_multiple_of
            batch_max_length = (
                (batch_max_length + multiple - 1)
                // multiple
                * multiple
            )

        # 4. Pad batch sequences
        batch_input_ids = []
        batch_labels = []

        for feature in combined_features:
            input_ids = feature["input_ids"]
            labels = feature["labels"]

            padding_length = batch_max_length - len(input_ids)

            padded_input_ids = input_ids + [self.eos_token_id] * padding_length
            padded_labels = labels + [self.eos_token_id] * padding_length

            batch_input_ids.append(padded_input_ids)
            batch_labels.append(padded_labels)

        # 5. Convert to tensors
        batch_input_ids_tensor = torch.tensor(batch_input_ids, dtype=torch.long)
        batch_labels_tensor = torch.tensor(batch_labels, dtype=torch.long)

        if self.device is not None:
            batch_input_ids_tensor = batch_input_ids_tensor.to(
                self.device, non_blocking=True
            )
            batch_labels_tensor = batch_labels_tensor.to(
                self.device, non_blocking=True
            )

        return {
            "input_ids": batch_input_ids_tensor,
            "labels": batch_labels_tensor,
        }

