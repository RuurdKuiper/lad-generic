class OffsetCallbackWrapper(TrainerCallback):
    def __init__(self, original_callback, step_offset):
        self.original = original_callback
        self.offset = step_offset

    def _with_offset(self, method_name, args, state, control, **kwargs):
        # Temporarily fake the global step for the callback
        original_step = state.global_step
        state.global_step = original_step + self.offset

        # Trigger the original callback
        if hasattr(self.original, method_name):
            getattr(self.original, method_name)(args, state, control, **kwargs)

        # Revert back so HF Trainer continues normally
        state.global_step = original_step

    def on_log(self, args, state, control, **kwargs):
        self._with_offset("on_log", args, state, control, **kwargs)

    def on_evaluate(self, args, state, control, **kwargs):
        self._with_offset("on_evaluate", args, state, control, **kwargs)

    def on_step_end(self, args, state, control, **kwargs):
        self._with_offset("on_step_end", args, state, control, **kwargs)

