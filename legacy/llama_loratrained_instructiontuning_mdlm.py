## Adaptive length data collator

@dataclass
class DiffusionDataCollator:
    eos_token_id: int
    device: torch.device | None = None
    pad_to_multiple_of: int | None = None

    def _remove_extra_eos_padding(
        self,
        input_ids: list[int],
        labels: list[int],
    ) -> tuple[list[int], list[int]]:
        """
        Remove repeated EOS padding while preserving one EOS token
        marking the actual end of the sequence.
        """
        if len(input_ids) != len(labels):
            raise ValueError(
                "input_ids and labels must have equal lengths."
            )

        end = len(input_ids)

        # Remove trailing EOS tokens, but preserve one final EOS.
        while (
            end > 1
            and input_ids[end - 1] == self.eos_token_id
            and input_ids[end - 2] == self.eos_token_id
        ):
            end -= 1

        return input_ids[:end], labels[:end]

    def __call__(
        self,
        features: List[Dict[str, Any]],
    ) -> Dict[str, torch.Tensor]:

        trimmed_features = []

        for feature in features:
            input_ids = list(feature["input_ids"])
            labels = list(feature["labels"])

            input_ids, labels = self._remove_extra_eos_padding(
                input_ids,
                labels,
            )

            trimmed_features.append(
                {
                    "input_ids": input_ids,
                    "labels": labels,
                }
            )

        batch_max_length = max(
            len(feature["input_ids"])
            for feature in trimmed_features
        )

        if self.pad_to_multiple_of is not None:
            multiple = self.pad_to_multiple_of
            batch_max_length = (
                (batch_max_length + multiple - 1)
                // multiple
                * multiple
            )

        batch_input_ids = []
        batch_labels = []

        for feature in trimmed_features:
            input_ids = feature["input_ids"]
            labels = feature["labels"]

            padding_length = batch_max_length - len(input_ids)

            # LLaDA-style EOS padding: these remain ordinary targets.
            padded_input_ids = (
                input_ids
                + [self.eos_token_id] * padding_length
            )

            padded_labels = (
                labels
                + [self.eos_token_id] * padding_length
            )

            batch_input_ids.append(padded_input_ids)
            batch_labels.append(padded_labels)

        batch_input_ids = torch.tensor(
            batch_input_ids,
            dtype=torch.long,
        )

        batch_labels = torch.tensor(
            batch_labels,
            dtype=torch.long,
        )

        if self.device is not None:
            batch_input_ids = batch_input_ids.to(
                self.device,
                non_blocking=True,
            )
            batch_labels = batch_labels.to(
                self.device,
                non_blocking=True,
            )

        return {
            "input_ids": batch_input_ids,
            "labels": batch_labels,
        }


