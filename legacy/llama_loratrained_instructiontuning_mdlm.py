def build_ngram_table_from_dataset(dataset, n=3, max_samples=None):
    """
    Build n-gram log-prob table from a tokenized dataset.

    dataset[i]['labels'] must be a list of token IDs.
    """
    counts = defaultdict(int)
    context_counts = defaultdict(int)

    total_samples = len(dataset) if max_samples is None else min(len(dataset), max_samples)

    for i in range(total_samples):
        tokens = dataset[i]["labels"]

        # Optional: remove -100 (common in HF labels)
        tokens = [t for t in tokens if t != -100]

        if len(tokens) < n:
            continue

        for j in range(len(tokens) - n + 1):
            ngram = tuple(tokens[j:j+n])
            context = tuple(tokens[j:j+n-1])

            counts[ngram] += 1
            context_counts[context] += 1

    # Convert to log-probs
    table = {}
    for ngram, c in counts.items():
        context = ngram[:-1]
        table[ngram] = np.log(c / context_counts[context])

    return table

