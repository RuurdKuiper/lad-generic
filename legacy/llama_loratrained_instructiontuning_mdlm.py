def get_bigram_score(prev_token, curr_token):
    # Very cheap heuristic instead of full LM:
    # reward space-consistent / punctuation-consistent transitions
    prev = tokenizer.decode([prev_token])
    curr = tokenizer.decode([curr_token])

    score = 0.0

    # simple heuristics (fast)
    if prev.endswith(" ") and curr.startswith(" "):
        score -= 0.5
    if prev.endswith((".", "!", "?")):
        if not curr.strip().startswith((" ", "\n")):
            score -= 0.3
    if prev.strip() == "" and curr.strip() == "":
        score -= 0.5

    # encourage letter continuity
    if prev and curr and prev[-1].isalpha() and curr[0].isalpha():
        score += 0.1

    return score

