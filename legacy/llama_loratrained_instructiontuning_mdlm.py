def decode_clean(ids, tokenizer):
    text = tokenizer.decode(ids, skip_special_tokens=False)
    text = re.sub(r'(<\|eot_id\|>)+$', '', text).strip()
    return text

def parse_llama3_chat(text):
    pattern = r'<\|start_header_id\|>(.*?)<\|end_header_id\|>\n(.*?)(?=<\|start_header_id\|>|<\|eot_id\|>|$)'
    segments = []
    for m in re.finditer(pattern, text, re.DOTALL):
        role    = m.group(1).strip()
        content = m.group(2).strip()
        if content:
            segments.append((role, content))
    return segments

def word_diff_html(source, target):
    src_words = source.split()
    tgt_words = target.split()
    matcher   = difflib.SequenceMatcher(None, src_words, tgt_words, autojunk=False)
    src_html, tgt_html = [], []

    def render_words(words, color=None):
        parts = []
        for w in words:
            # Split on MASK boundaries, keeping MASK as a token
            segments = re.split(r'(MASK)', w)
            rendered = ""
            for seg in segments:
                if seg == "MASK":
                    rendered += '<span style="background:#ff9800;color:white;border-radius:3px;padding:1px 5px;font-weight:bold">MASK</span>'
                elif seg:
                    if color:
                        rendered += f'<span style="background:{color};border-radius:3px;padding:1px 4px">{seg}</span>'
                    else:
                        rendered += seg
            parts.append(rendered)
        return " ".join(parts)

    for op, i1, i2, j1, j2 in matcher.get_opcodes():
        if op == "equal":
            src_html.append(render_words(src_words[i1:i2]))
            tgt_html.append(render_words(tgt_words[j1:j2]))
        elif op == "replace":
            src_html.append(render_words(src_words[i1:i2], "#ffcccc"))
            tgt_html.append(render_words(tgt_words[j1:j2], "#ccffcc"))
        elif op == "delete":
            src_html.append(render_words(src_words[i1:i2], "#ffcccc"))
        elif op == "insert":
            tgt_html.append(render_words(tgt_words[j1:j2], "#ccffcc"))

    return " ".join(src_html), " ".join(tgt_html)

